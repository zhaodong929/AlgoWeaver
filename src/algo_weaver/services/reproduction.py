class ReproductionPlanner:
    """Build an evidence-linked plan without asking a model to invent code."""

    def build_plan(
        self,
        capability: AlgorithmCapability,
        hits: Iterable[RetrievalHit] = (),
    ) -> ReproductionPlan:
        retrieval_hits = list(hits)
        chunk_ids = [hit.chunk.chunk_id for hit in retrieval_hits]
        source_ids = [evidence.source_id for evidence in capability.evidence]
        blocking_reasons: list[str] = []
        for label, value in (
            ("problem_definition", capability.problem_definition.strip()),
            ("inputs", capability.inputs),
            ("outputs", capability.outputs),
            ("algorithm_steps", capability.algorithm_steps),
        ):
            if not value:
                blocking_reasons.append(f"missing {label}")
        if not source_ids and not chunk_ids:
            blocking_reasons.append("no source evidence or retrieval hit")

        steps = [
            ReproductionStep(
                step_id=f"step_{index:02d}",
                description=description,
                evidence_chunk_ids=chunk_ids,
                acceptance_checks=["source evidence remains attached"],
            )
            for index, description in enumerate(capability.algorithm_steps, start=1)
        ]
        if not steps:
            steps = [
                ReproductionStep(
                    step_id="step_01",
                    description="Resolve the missing algorithm steps before generation.",
                    evidence_chunk_ids=chunk_ids,
                    acceptance_checks=["plan is reviewed by a human"],
                )
            ]

        return ReproductionPlan(
            capability_id=capability.capability_id,
            capability_name=capability.name,
            algorithm_family=capability.algorithm_family,
            objective=capability.problem_definition or "Reproduce the described algorithm.",
            required_inputs=capability.inputs,
            expected_outputs=capability.outputs,
            dependencies=["python>=3.12"],
            steps=steps,
            evidence_source_ids=source_ids,
            evidence_chunk_ids=chunk_ids,
            acceptance_checks=[
                "Python syntax check",
                "required interface check",
                "independent tests before verified promotion",
            ],
            status="blocked" if blocking_reasons else "ready",
            blocking_reasons=blocking_reasons,
        )


class TemplateArtifactWriter:
    """Write deterministic demo artifacts; never executes generated source."""

    def generate(self, plan: ReproductionPlan) -> ReproductionBundle:
        if plan.status != "ready":
            raise ValueError("cannot generate artifacts from a blocked reproduction plan")
        function_name = _function_name(plan.capability_name, plan.algorithm_family)
        source = _source_template(function_name, plan)
        test = _test_template(function_name)
        return ReproductionBundle(
            plan=plan,
            artifacts=[
                _artifact("algorithm.py", "python_source", source),
                _artifact("test_algorithm.py", "pytest_test", test),
            ],
        )

    def write(self, bundle: ReproductionBundle, output_dir: str | Path) -> list[Path]:
        destination = Path(output_dir)
        destination.mkdir(parents=True, exist_ok=True)
        paths: list[Path] = []
        for artifact in bundle.artifacts:
            path = destination / artifact.path
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(artifact.content, encoding="utf-8")
            paths.append(path)
        return paths


def _function_name(name: str, family: str) -> str:
    normalized = f"{name} {family}".lower()
    if "moving average" in normalized or "移动平均" in normalized or "time_series" in normalized:
        return "moving_average"
    return "run_algorithm"


