def _artifact(path: str, kind: str, content: str) -> GeneratedArtifact:
    artifact_kind = cast(ArtifactKind, kind)
    return GeneratedArtifact(
        path=path,
        kind=artifact_kind,
        content=content,
        content_sha256=hashlib.sha256(content.encode("utf-8")).hexdigest(),
    )
